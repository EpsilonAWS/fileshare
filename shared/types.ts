/**
 * shared/types.ts — API contract between frontend (app/, components/, lib/)
 * and backend (app/api/, server/). Change this file together, never alone.
 *
 * END-TO-END ENCRYPTION, with the passkey mixed into the key.
 * All crypto runs in the browser (lib/crypto.ts). The server never sees the
 * link secret, the passkey, the file key, or any plaintext.
 *
 *   linkSecret  = 32 random bytes            → lives only in the link's #fragment
 *   passkeyKey  = PBKDF2-SHA256(passkey, salt, PBKDF2_ITERATIONS)   (if passkey set)
 *   ikm         = linkSecret || passkeyKey   (or just linkSecret if no passkey)
 *   fileKey     = HKDF-SHA256(ikm, info="fileshare/enc")  → AES-256-GCM key
 *   authToken   = HKDF-SHA256(ikm, info="fileshare/auth") → sent to server instead of passkey
 *
 * - The file and its metadata are encrypted with fileKey (separate random IVs).
 * - The server stores argon2(authToken) and checks it on /unlock. Because
 *   authToken also depends on linkSecret, a leaked database can't be used to
 *   brute-force the passkey, and a leaked link can't decrypt without the passkey.
 * - Lost passkey or lost #fragment = file is unrecoverable. That is by design.
 *
 * All timestamps are ISO 8601 UTC strings. Responses include `serverTime` so the
 * receiver's countdown uses the server's clock, not the device's.
 */

// ─── Policy options ────────────────────────────────────────────────────────

export const EXPIRY_OPTIONS = ["10m", "1h", "24h"] as const;
export type ExpiryOption = (typeof EXPIRY_OPTIONS)[number];

export const EXPIRY_SECONDS: Record<ExpiryOption, number> = {
  "10m": 10 * 60,
  "1h": 60 * 60,
  "24h": 24 * 60 * 60,
};

export const DOWNLOAD_LIMIT_OPTIONS = [1, 3, 10] as const;
export type DownloadLimit = (typeof DOWNLOAD_LIMIT_OPTIONS)[number];

/** Plaintext limit enforced in the browser before encryption. */
export const MAX_UPLOAD_BYTES = 100 * 1024 * 1024;
/** Server-side limit: plaintext limit + room for IV/auth tags/meta overhead. */
export const MAX_CIPHERTEXT_BYTES = MAX_UPLOAD_BYTES + 1024 * 1024;

export const PASSKEY_MIN_LENGTH = 6;
export const MAX_PASSKEY_ATTEMPTS = 5;

/** Random bytes in the link's #fragment. */
export const LINK_SECRET_BYTES = 32;
/** OWASP 2023+ recommendation for PBKDF2-SHA256. ~0.3–1s on a phone. */
export const PBKDF2_ITERATIONS = 600_000;

/** Public key-derivation parameters. Safe to reveal before unlock. */
export interface KdfParams {
  algorithm: "PBKDF2-SHA256";
  iterations: number;
  /** base64url, 16 random bytes, generated by the browser. */
  salt: string;
}

/** How long the presigned PUT URL stays valid. */
export const UPLOAD_URL_TTL_SECONDS = 15 * 60;
/** How long the presigned GET URL stays valid after unlock. */
export const DOWNLOAD_URL_TTL_SECONDS = 60;
/** How long the access token from /unlock stays valid. */
export const ACCESS_TOKEN_TTL_SECONDS = 5 * 60;

// ─── Endpoints ─────────────────────────────────────────────────────────────

export const API = {
  createUpload: () => `/api/uploads`, //                       POST
  completeUpload: (uploadId: string) => `/api/uploads/${uploadId}/complete`, // POST
  vaultStatus: (token: string) => `/api/vault/${token}`, //      GET
  unlock: (token: string) => `/api/vault/${token}/unlock`, //    POST
  download: (token: string) => `/api/vault/${token}/download`, // POST
} as const;

// ─── 1. Create upload ──────────────────────────────────────────────────────
// POST /api/uploads
// Creates a pending record and returns a presigned PUT URL.
// The file is NOT accessible until /complete succeeds.

export interface CreateUploadRequest {
  /** Size of the ciphertext the browser will PUT, in bytes. */
  sizeBytes: number;
  expiry: ExpiryOption;
  maxDownloads: DownloadLimit;
  /**
   * Present only if the sender set a passkey. The raw passkey is NEVER sent.
   * Server stores argon2(authToken) + kdf, and returns kdf from /vault/:token.
   */
  passkeyProtection?: {
    /** base64url, 32 bytes, derived in the browser (see header). */
    authToken: string;
    kdf: KdfParams;
  };
  /** base64url of AES-GCM(iv || ciphertext) of EncryptedMetaPlain. Max 4 KB. */
  encryptedMeta: string;
}

export interface CreateUploadResponse {
  uploadId: string;
  /** Final share token for /vault/:shareToken (not usable until complete). */
  shareToken: string;
  /** Presigned S3/R2 PUT URL. Browser uploads ciphertext directly here. */
  uploadUrl: string;
  /** Headers the browser must send with the PUT (e.g. Content-Type). */
  uploadHeaders: Record<string, string>;
  uploadUrlExpiresAt: string;
}

// ─── 2. Complete upload ────────────────────────────────────────────────────
// POST /api/uploads/:uploadId/complete
// Server verifies the object exists in storage and its size matches.
// The expiry clock STARTS here, not at create time.

export interface CompleteUploadResponse {
  shareToken: string;
  expiresAt: string;
  maxDownloads: DownloadLimit;
  serverTime: string;
}

// ─── 3. Vault status ───────────────────────────────────────────────────────
// GET /api/vault/:token
// Reveals nothing about the file — only whether a passkey is needed.
// Errors: NOT_FOUND, EXPIRED, EXHAUSTED, LOCKED_OUT.

export interface VaultStatusResponse {
  requiresPasskey: boolean;
  /** Present when requiresPasskey is true. The browser needs it to derive keys. */
  kdf?: KdfParams;
  serverTime: string;
}

// ─── 4. Unlock ─────────────────────────────────────────────────────────────
// POST /api/vault/:token/unlock
// Called even when no passkey is set (send {}). Returns metadata + a
// short-lived access token used for the download call.
// Server compares argon2(authToken) to the stored hash; a mismatch is WRONG_PASSKEY.
// Errors: PASSKEY_REQUIRED, WRONG_PASSKEY, LOCKED_OUT, EXPIRED, EXHAUSTED, RATE_LIMITED.

export interface UnlockRequest {
  /** Derived in the browser from linkSecret + passkey + kdf. Omit if no passkey. */
  authToken?: string;
}

export interface UnlockResponse {
  /** Send as `Authorization: Bearer <accessToken>` to /download. */
  accessToken: string;
  accessTokenExpiresAt: string;
  meta: VaultMetadata;
}

export interface VaultMetadata {
  /** Decrypt in the browser with the #fragment key → EncryptedMetaPlain. */
  encryptedMeta: string;
  /** Ciphertext size; show as approximate file size. */
  sizeBytes: number;
  expiresAt: string;
  downloadsRemaining: number;
  maxDownloads: DownloadLimit;
  serverTime: string;
}

// ─── 5. Download ───────────────────────────────────────────────────────────
// POST /api/vault/:token/download   (Authorization: Bearer <accessToken>)
// Atomically decrements the count, then returns a presigned GET URL.
// The count is consumed when the URL is issued, not when the download finishes.
// Errors: ACCESS_TOKEN_INVALID, EXPIRED, EXHAUSTED.

export interface DownloadResponse {
  downloadUrl: string;
  downloadUrlExpiresAt: string;
  /** After this download. 0 means the file is now revoked. */
  downloadsRemaining: number;
}

// ─── Errors ────────────────────────────────────────────────────────────────
// Every non-2xx response has this body. The frontend switches on `code`,
// never on `message` (message is for logs/devs only).

export const ERROR_STATUS = {
  VALIDATION_ERROR: 400,
  PASSKEY_REQUIRED: 401,
  WRONG_PASSKEY: 401,
  ACCESS_TOKEN_INVALID: 401,
  NOT_FOUND: 404,
  UPLOAD_INCOMPLETE: 409,
  EXPIRED: 410,
  EXHAUSTED: 410,
  FILE_TOO_LARGE: 413,
  LOCKED_OUT: 423,
  RATE_LIMITED: 429,
  STORAGE_ERROR: 502,
  INTERNAL: 500,
} as const;

export type ErrorCode = keyof typeof ERROR_STATUS;

export interface ErrorDetails {
  /** WRONG_PASSKEY: tries left before LOCKED_OUT. */
  attemptsRemaining?: number;
  /** RATE_LIMITED / LOCKED_OUT: seconds until retry is allowed. */
  retryAfterSeconds?: number;
  /** VALIDATION_ERROR: which fields failed. */
  fields?: Record<string, string>;
}

export interface ApiError {
  error: {
    code: ErrorCode;
    message: string;
    details?: ErrorDetails;
  };
}

// ─── Client-only (never sent to the server in plaintext) ──────────────────

/** What gets encrypted into `encryptedMeta`. */
export interface EncryptedMetaPlain {
  /** Display name. For multi-file uploads, e.g. "fileshare-3-files.zip". */
  name: string;
  contentType: string;
  /** Original plaintext size in bytes. */
  size: number;
  /** Present when several files were zipped in the browser. */
  files?: { name: string; size: number }[];
}
